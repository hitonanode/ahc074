using u64 = std::uint64_t;

// Canonicalize by (outdegree, indegree), enumerating only permutations inside
// equal-degree classes. Equal in/out-neighborhoods are interchangeable twins.
u64 canonical7(u64 r) {
    unsigned out[7], in[7]{};
    int key[7], order[7];
    for (int a=0;a<7;a++) {
        out[a]=(r>>(8*a))&127;
        for (int b=0;b<7;b++) if(out[a]>>b&1) in[b]|=1U<<a;
    }
    for(int a=0;a<7;a++) key[a]=__builtin_popcount(out[a])*8+__builtin_popcount(in[a]);
    u64 best=~0ULL;
    auto dfs=[&](auto&& self,int k,unsigned used)->void {
        if(k==7) {
            u64 rr=0;
            for(int i=0;i<7;i++) for(int j=0;j<7;j++)
                if(out[order[i]]>>order[j]&1) rr|=1ULL<<(8*i+j);
            best=std::min(best,rr); return;
        }
        int smallest=1000;
        for(int a=0;a<7;a++)if(!(used>>a&1))smallest=std::min(smallest,key[a]);
        unsigned tried=0;
        for(int a=0;a<7;a++)if(!(used>>a&1)&&key[a]==smallest) {
            bool twin=false;
            for(int b=0;b<a;b++)if(tried>>b&1) twin|=out[a]==out[b]&&in[a]==in[b];
            if(twin)continue;
            tried|=1U<<a;order[k]=a;self(self,k+1,used|(1U<<a));
        }
    };
    dfs(dfs,0,0);return best;
}

int main(int argc,char**argv) {
    if(argc!=2) {std::cerr<<"usage: generate_posets astra-search4/main.cpp\n";return 2;}
    std::ifstream file(argv[1]);std::string source((std::istreambuf_iterator<char>(file)),{});
    auto b=source.find("constexpr PosetClass kPosetClasses[318]");
    auto e=source.find("\n};",b);assert(b!=std::string::npos&&e!=std::string::npos);
    std::unordered_set<u64> distinct;
    for(std::size_t p=b;(p=source.find("0x",p))<e;p+=2) {
        u64 r=std::stoull(source.substr(p),nullptr,16);
        for(unsigned s=0;s<64;s++) {
            bool ideal=true;
            for(int a=0;a<6;a++) if(!(s>>a&1)&&(((r>>(8*a))&63)&s))ideal=false;
            if(!ideal)continue;
            u64 q=r;
            for(int a=0;a<6;a++)if(s>>a&1)q|=1ULL<<(8*a+6);
            distinct.insert(canonical7(q));
        }
    }
    std::vector<u64> classes(distinct.begin(),distinct.end());
    std::sort(classes.begin(),classes.end());
    std::cerr<<"classes="<<classes.size()<<'\n';assert(classes.size()==2045);
    std::vector<std::array<int,7>> permutations;
    std::array<int,7> p{0,1,2,3,4,5,6};
    do permutations.push_back(p);while(std::next_permutation(p.begin(),p.end()));
    std::vector<std::vector<int>> pred(5040);
    std::vector<u64> orderbits(5040);
    for(int s=0;s<5040;s++) {
        for(int i=0;i<7;i++)for(int j=i+1;j<7;j++)
            orderbits[s]|=1ULL<<(8*permutations[s][i]+permutations[s][j]);
        for(int i=0;i<6;i++)for(int j=0;j<7;j++)if(i!=j) {
            auto q=permutations[s];int v=q[i];
            if(i<j)for(int t=i;t<j;t++)q[t]=q[t+1];
            else for(int t=i;t>j;t--)q[t]=q[t-1];
            q[j]=v;
            int to=std::lower_bound(permutations.begin(),permutations.end(),q)-permutations.begin();
            pred[to].push_back(s);
        }
    }
    std::vector<int> sums;
    for(u64 r:classes) {
        std::array<unsigned char,5040> distance;distance.fill(255);
        std::array<int,5040> queue{};int head=0,tail=0;
        for(int s=0;s<5040;s++)if(!(r&~orderbits[s]))distance[s]=0,queue[tail++]=s;
        while(head<tail) {
            int s=queue[head++];
            for(int t:pred[s])if(distance[t]==255)distance[t]=distance[s]+1,queue[tail++]=t;
        }
        assert(tail==5040);int sum=std::accumulate(distance.begin(),distance.end(),0);
        sums.push_back(sum);
    }
    std::cout<<"// Generated by generate_posets.cpp; all 2045 unlabeled 7-element posets.\n";
    std::cout<<"// Each cost is the sum over all 5040 source permutations of the shortest\n";
    std::cout<<"// legal insertion distance to a linear extension of this relation.\n";
    std::cout<<"constexpr PosetClass kPoset7Classes[2045] = {\n";
    for(std::size_t i=0;i<classes.size();i++)std::cout<<"{0x"<<std::hex<<classes[i]<<"ULL, "<<std::dec<<sums[i]<<"},\n";
    std::cout<<"};\n";
}
