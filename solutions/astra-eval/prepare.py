#!/usr/bin/env python3
"""Create an isolated, reproducible evaluation checkout without replacing official inputs."""
import argparse
from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[2]

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('destination', type=Path, help='A new directory that does not exist yet')
    parser.add_argument('--count', type=int, default=2000)
    args = parser.parse_args()
    destination = args.destination.resolve()
    if destination.exists():
        parser.error('Destination already exists; choose a new directory')
    if args.count < 1:
        parser.error('--count must be positive')
    destination.mkdir(parents=True)
    for name in ['AGENTS.md', 'pahcer_config.toml', '.gitignore']:
        shutil.copy2(ROOT/name, destination/name)
    shutil.copytree(ROOT/'scripts', destination/'scripts', ignore=shutil.ignore_patterns('__pycache__'))
    (destination/'tools/src/bin').mkdir(parents=True)
    for name in ['tools/Cargo.toml', 'tools/src/lib.rs', 'tools/src/bin/tester.rs', 'tools/src/bin/gen.rs']:
        shutil.copy2(ROOT/name, destination/name)
    # Copy source files and descriptions, never local binaries or old measurement outputs.
    folders = [ROOT/'solutions/imp-gla', ROOT/'solutions/astra-eval',
               ROOT/'solutions/astra-options', ROOT/'solutions/astra-triples']
    folders += sorted((ROOT/'solutions').glob('astranova-*'))
    folders += sorted((ROOT/'solutions').glob('astrasearch-*'))
    for folder in folders:
        target = destination/'solutions'/folder.name
        target.mkdir(parents=True)
        for file in folder.rglob('*'):
            relative = file.relative_to(folder)
            if not file.is_file() or any(part in {'results', '__pycache__', 'fixtures'} for part in relative.parts):
                continue
            if folder.name.startswith('astrasearch-') and file.name not in {'main.cpp', 'README.md'}:
                continue
            if file.suffix not in {'.cpp', '.py', '.md', '.json', '.csv', '.txt'} and file.name != '.gitignore':
                continue
            # reference-output is needed to reproduce the structural probes;
            # timing-dependent baseline designs cannot be regenerated byte for byte.
            output = target/relative
            output.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(file, output)
    subprocess.run(['git', 'init', '-q', '-b', 'research'], cwd=destination, check=True)
    binary = destination/'tools/target/release/tester'
    binary.parent.mkdir(parents=True)
    subprocess.run(['g++', '-std=c++23', '-O2', 'solutions/astra-eval/tester.cpp', '-o', str(binary)],
                   cwd=destination, check=True)
    subprocess.run(['python3', 'solutions/astra-eval/generate.py', '--count', str(args.count)],
                   cwd=destination, check=True)
    print(f'Prepared {destination}')
    print('Run the compare.py commands from that directory. The original repository inputs were not changed.')

if __name__ == '__main__':
    main()
